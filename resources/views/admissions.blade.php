        <!-- ENGLISH LANGUAGE REQUIREMENTS -->
        <section class="admission-section">
            <h2>English Language Proficiency</h2>

            <div class="admission-card">
                <h3>Non-English Speaking Candidates</h3>
                <p>
                    English is the language of instruction at UCC. If your most
                    recent education was not in English, or English is not your
                    first language, you may need to show English proficiency
                    through an approved test such as the TOEFL.
                </p>
                <ul>
                    <li>Both paper-based (PBT) and internet-based (IBT) TOEFL are accepted.</li>
                    <li>A TOEFL score of 500, no more than two years old, is accepted in place of a CXC/GCE English Language pass.</li>
                    <li>TOEFL costs are paid by the applicant, and UCC may also require its own English proficiency test.</li>
                </ul>
                <p>
                    More information is on the official
                    <a href="https://www.ets.org/toefl" target="_blank" rel="noopener noreferrer">TOEFL website.</a>
                </p>
            </div>
