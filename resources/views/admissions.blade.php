        <!-- ENGLISH LANGUAGE REQUIREMENTS -->
        <section class="admission-section">

            <h2>English Language Proficiency</h2>

            <div class="admission-card">

                <h3>Non-English Speaking Candidates</h3>

                <p>
                    English is the language of instruction at UCC.
                    Applicants whose most recent education was not
                    conducted in English, or whose first language
                    is not English, may be required to demonstrate
                    English language proficiency.
                </p>

                <p>
                    An approved English testing examination, such
                    as the Test of English as a Foreign Language
                    (TOEFL), may be required.
                </p>

                <ul>

                    <li>
                        UCC Global accepts both TOEFL Paper-Based
                        Testing (PBT) and Internet-Based Testing (IBT).
                    </li>

                    <li>
                        The supplied international admissions information
                        states that a TOEFL score of 500, not exceeding
                        two years old, will be accepted as equivalent to
                        an acceptable CXC/GCE English Language pass.
                    </li>

                    <li>
                        All costs associated with TOEFL testing must
                        be paid by the applicant.
                    </li>

                    <li>
                        UCC reserves the right to require applicants
                        to complete its own English Language
                        Proficiency Test in addition to TOEFL.
                    </li>

                </ul>

                <p>
                    For further information, visit the official
                    <a href="https://www.ets.org/toefl"
                       target="_blank"
                       rel="noopener noreferrer">
                        TOEFL website.
                    </a>
                </p>

            </div>

        </section>


