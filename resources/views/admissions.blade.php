            <h2>Undergraduate Admission Requirements</h2>

            <p class="section-description">
                Applicants seeking admission to undergraduate programmes
                should satisfy the following academic requirements.
            </p>

            <div class="admission-card">

                <h3>Academic Qualifications</h3>

                <ul>
                    <li>
                        A minimum of five (5) subjects at CSEC General
                        Proficiency, Grades 1, 2 or 3, or GCE O-Level,
                        Grades A, B or C.
                    </li>

                    <li>
                        English Language and Mathematics must be included.
                    </li>

                    <li>
                        A CSEC Grade 3 must have been obtained in or after
                        June 1998.
                    </li>

                    <li>
                        Principles of Accounts is required for applicable
                        business programmes.
                    </li>

                    <li>
                        Equivalent international qualifications may be
                        considered, subject to UCC approval.
                    </li>
                </ul>

            </div>


